WIDTH = 78


def _one_line(text) -> str:
    """Device-supplied text on one line, without control characters."""
    return " ".join("".join(ch if ch.isprintable() else " " for ch in str(text or "")).split())


def _when(ts: Optional[int]) -> Optional[str]:
    if not ts:
        return None
    return datetime.fromtimestamp(ts, tz=timezone.utc).astimezone().strftime("%Y-%m-%d %H:%M:%S %Z").strip()


def _section(out: list[str], title: str) -> None:
    out += ["", "=" * WIDTH, title, "=" * WIDTH]


def _version(p) -> str:
    return _one_line(" ".join(x for x in (p.product, p.version, f"({p.extrainfo})" if p.extrainfo else "") if x))


def _port_name(f) -> str:
    return f"{f.port}/{f.protocol}" if f.port is not None else "-"


def technical_report(a: Analysis, lang: str = "ro", changes: Optional[dict] = None,
                     now: Optional[datetime] = None) -> str:
    """The whole report as text (UTF-8, \\n line ends). `changes` is history.changes() against the previous check."""
    lang = lang if lang in LANGS else "ro"
    t = L[lang]
    now = now or datetime.now().astimezone()
    out: list[str] = [t["title"], "-" * WIDTH]

    def kv(k, v):
        out.append(f"{k + ':':<26} {v}")

    kv(t["file"], a.file)
    if not a.ok:
        kv("ERROR", _one_line(a.error))
        out.append("")
        return "\n".join(out)
    scan = a.scan
    kv(t["started"], _when(scan.start_time) or t["unknown"])
    if scan.args:
        kv(t["args"], _one_line(scan.args))
    kv(t["generated"], now.strftime("%Y-%m-%d %H:%M:%S %Z").strip())
    kv(t["tool"], f"SafeHouse {__version__}")

    hosts = sorted(scan.up_hosts, key=lambda h: _ip_key(h.ip))
    findings = sorted(a.findings, key=lambda f: (-SEVERITY_RANK[f.severity], -f.points, f.sort_key))
    risk = device_risk(a.findings)

    # ---- summary
    _section(out, t["summary"])
    band = score_band(a.score, lang)
    kv(t["score"], f"{a.score}/100 ({band['label']})")
    pts = [f.points for f in findings if f.points]
    kv(t["formula"], f"max(0, 100 - ({' + '.join(map(str, pts)) or '0'})) = {a.score}")
    kv(t["hosts"], str(len(hosts)))
    kv(t["ports"], str(sum(len(h.open_ports) for h in hosts)))
    counts = {k: sum(1 for f in findings if f.severity == k) for k in ("high", "medium", "low", "info")}
    kv(t["findings"], f"{len(findings)}  (" + ", ".join(f"{t['sev'][k]}: {n}" for k, n in counts.items()) + ")")
    if risk and max(risk.values()) > 0:
        ip = max(sorted(risk, key=_ip_key), key=lambda i: risk[i])
        h = next((x for x in hosts if x.ip == ip), None)
        label = DEVICE_LABELS[guess_type(h)][lang] if h else ""
        kv(t["worst"], f"{ip} ({label}{', ' + h.vendor if h and h.vendor else ''}) - {risk[ip]} {t['risk'].lower()}")

    # ---- findings table
    _section(out, t["table"])
    if not findings:
        out.append(t["none"])
    else:
        rows = [t["cols"]] + [(str(i), t["sev"][f.severity].upper(), str(f.points), f.ip, _port_name(f), f.code,
                               _one_line(f.evidence)) for i, f in enumerate(findings, 1)]
        w = [max(len(r[c]) for r in rows) for c in range(6)]
        for r in rows:
            out.append("  ".join(r[c].ljust(w[c]) for c in range(6)) + "  " + r[6])

    # ---- hosts, nmap style
    _section(out, t["hostsec"])
    for h in hosts:
        out.append("")
        name = _one_line(h.hostname) if h.hostname else ""
        out.append(f"{t['report_for']} {name} ({h.ip})" if name else f"{t['report_for']} {h.ip}")
        out.append(t["up"])
        if h.mac:
            out.append(f"{t['mac']}: {mask_mac(h.mac)}" + (f" ({_one_line(h.vendor)})" if h.vendor else ""))
        if h.os_guess:
            out.append(f"{t['os']}: {_one_line(h.os_guess)}")
        out.append(f"{t['type']}: {DEVICE_LABELS[guess_type(h)][lang]}    {t['risk']}: {risk.get(h.ip, 0)}")
        ports = sorted(h.open_ports, key=lambda p: (p.protocol, p.portid))
        if not ports:
            out.append(t["noports"])
        else:
            rows = [t["pcols"]] + [(f"{p.portid}/{p.protocol}", p.state, (p.service or "unknown") + ("/ssl" if p.tunnel == "ssl" else ""),
                                    _version(p)) for p in ports]
            w = [max(len(r[c]) for r in rows) for c in range(3)]
            for r, p in zip(rows, [None] + ports):
                out.append("  ".join(r[c].ljust(w[c]) for c in range(3)) + "  " + r[3])
                if p is not None and p.http_title:
                    out.append(f"|_ {t['pagetitle']}: {_one_line(p.http_title)}")
        mine = [f for f in findings if f.ip == h.ip]
        if mine:
            out.append(f"{t['onhost']}:")
            for f in mine:
                out.append(f"  - [{t['sev'][f.severity].upper()} {f.points}] {f.code} {_port_name(f)}: {_one_line(f.evidence)}")

    # ---- remediation, once per finding code
    if findings:
        _section(out, t["remed"])
        for code in dict.fromkeys(f.code for f in findings):
            tx, entry = text_for(code, lang), CATALOG[code]
            where = ", ".join(f"{f.ip}:{f.port}" if f.port is not None else f.ip for f in findings if f.code == code)
            out += ["", f"[{code}] {tx['title']}  ({t['sevword']}: {t['sev'][entry.severity]}, {entry.points} pt)",
                    f"  {t['affected']}: {where}", f"  {t['what']}: {tx['explain']}", f"  {t['steps']}:"]
            out += [f"    {i}. {s}" for i, s in enumerate(tx["steps"], 1)]
            if tx.get("refs"):
                out.append(f"  {t['refs']}: {', '.join(tx['refs'])}")

    # ---- before / after
    if changes:
        _section(out, t["changes"])
        d = changes
        kv(t["prev"], f"{d['before_file']} ({d['score_before']}/100) -> {d['score_after']}/100 ({d['score_change']:+d})")
        fmt_f = lambda xs: ", ".join(f"{x['code']} {x['ip']}" + (f":{x['port']}" if x["port"] is not None else "") for x in xs) or t["nothing"]
        fmt_p = lambda xs: ", ".join(f"{x['ip']}:{x['port']}/{x['protocol']} {x['service']}" for x in xs) or t["nothing"]
        kv(t["fixed"], fmt_f(d["resolved_findings"]))
        kv(t["new"], fmt_f(d["new_findings"]))
        kv(t["newdev"], ", ".join(d["new_devices"]) or t["nothing"])
        kv(t["gone"], ", ".join(d["removed_devices"]) or t["nothing"])
        kv(t["opened"], fmt_p(d["opened_ports"]))
        kv(t["closed"], fmt_p(d["closed_ports"]))

    _section(out, t["notes"])
    out += [f"- {t[k]}" for k in ("note1", "note2", "note3", "note4")]
    out.append("")
    return "\n".join(line.rstrip() for line in out)
