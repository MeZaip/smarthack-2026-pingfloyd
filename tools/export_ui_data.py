"""Build ui/data.js for the HTML demo from real tool output (no hand-written results).

    python tools/export_ui_data.py [scan-folder] [--history before.xml after.xml] [--out ui/data.js]

Defaults: every scan in tests/fixtures/synthetic, history = V6a_before -> V6b_after.
Everything comes from the same code as the CLI: rules, score, texts, diff.
MAC addresses are already masked by Analysis.devices() (NFR-02).
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from netcheck import history  # noqa: E402
from netcheck.core.analysis import analyze_file, scan_files_in  # noqa: E402
from netcheck.core.device import DEVICE_LABELS  # noqa: E402
from netcheck.explain.texts import LANGS, SEVERITY_LABELS, TEXTS, score_band  # noqa: E402

SYN = ROOT / "tests" / "fixtures" / "synthetic"


def scan_entry(path: Path) -> dict:
    a = analyze_file(path)
    if not a.ok:
        return {"file": a.file, "error": a.error}
    return {
        "file": a.file,
        "score": a.score,
        "band": score_band(a.score)["color"],
        "devices": a.devices(),
        "findings": [
            {"ip": f.ip, "port": f.port, "protocol": f.protocol, "code": f.code,
             "severity": f.severity, "points": f.points, "evidence": f.evidence}
            for f in a.prioritized()
        ],
    }


def history_entry(before: Path, after: Path) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        db = Path(tmp) / "history.sqlite"
        with history.open_history(db) as conn:
            for f in (before, after):
                history.save(conn, analyze_file(f))
            return {"trend": history.trend(conn), "changes": history.changes(conn)}


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("folder", nargs="?", default=str(SYN))
    p.add_argument("--history", nargs=2, metavar=("BEFORE", "AFTER"),
                   default=[str(SYN / "V6a_before.xml"), str(SYN / "V6b_after.xml")])
    p.add_argument("--out", default=str(ROOT / "ui" / "data.js"))
    args = p.parse_args(argv)

    data = {
        "scans": [scan_entry(f) for f in scan_files_in(args.folder)],
        "history": history_entry(Path(args.history[0]), Path(args.history[1])),
        "texts": {code: {**{lang: t[lang] for lang in LANGS}, "refs": t.get("refs", [])}
                  for code, t in TEXTS.items()},
        "severity": SEVERITY_LABELS,
        "deviceLabels": DEVICE_LABELS,
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, ensure_ascii=False, indent=1).replace("</", "<\\/")
    out.write_text("// Generated by tools/export_ui_data.py - do not edit by hand.\n"
                   f"window.NETCHECK_DATA = {body};\n", encoding="utf-8")
    print(f"Wrote {out} ({len(data['scans'])} scans)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
